CREATE TABLE accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_identifier VARCHAR(254) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(10) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_accounts_login_identifier UNIQUE (login_identifier),
    CONSTRAINT chk_accounts_login_identifier_normalized CHECK (
        login_identifier = lower(btrim(login_identifier)) AND length(login_identifier) > 0
    ),
    CONSTRAINT chk_accounts_role CHECK (role IN ('ADMIN', 'USER')),
    CONSTRAINT chk_accounts_password_hash CHECK (length(password_hash) > 0)
);

CREATE INDEX idx_accounts_enabled ON accounts (enabled);
